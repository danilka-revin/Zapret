#!/usr/bin/env bash
# Обёртка единственного ярлыка «Робот»: поднимает веб-пульт и экран киоска.
DIR="$(cd "$(dirname "$0")" && pwd)"

# При каждом запуске через ярлык кладём на рабочий стол актуальные прошивки
# колёс (по файлу на каждое): после обновления версии здесь появятся новые файлы.
# Ошибка копирования запуску робота не мешает.
"$DIR/sync_firmware_desktop.sh" || echo "⚠ Прошивки на рабочем столе не обновились — робот запускается дальше."
echo

"$DIR/start_robot.sh"
STATUS=$?

echo
if [[ $STATUS -ne 0 ]]; then
  echo "⚠ Запуск остановился с ошибкой (код $STATUS). Причина указана выше."
  echo "  Проверьте подключение, занятые порты 8080/8090 и права на USB-мастер."
else
  echo "✔ Запуск завершён."
fi
echo
read -r -p "Нажмите Enter, чтобы закрыть окно…"
